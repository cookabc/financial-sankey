export function detectLang() {
  try {
    const saved = localStorage.getItem(LANG_KEY);
    if (saved && dict[saved]) return saved;
  } catch {
    /* storage blocked: fall through to the document language */
  }
  const doc = (document.documentElement.lang || "").toLowerCase();
  return doc.startsWith("zh") ? "zh" : "en";
}

export function translator(lang) {
  const table = dict[lang] ?? dict.en;
  return (key, vars) => {
    let text = table[key] ?? dict.en[key] ?? key;
    if (vars)
      for (const [name, value] of Object.entries(vars)) text = text.replaceAll(`{${name}}`, String(value));
    return text;
  };
}

export { dict };

/** Palette display names follow the interface language; the palette ids do not. */
export function paletteLabel(t, id) {
  return t(`palette.${id}`);
}
